--- 05. ORDERS_SEQ 시퀀스 생성 ---
CREATE SEQUENCE ORDERS_SEQ
    INCREMENT BY 1
    START WITH   1000
    MINVALUE     1
    MAXVALUE     99999999
    NOCYCLE
    NOCACHE;

SELECT ORDERS_SEQ.NEXTVAL FROM dual;
